export const MAHRAM_RELATIONS: MahramRelation[] = ([ ["men", men], ["women", women] ] as const).flatMap(([audience, rows]) =>
  rows.map(([name, status, category, note = "", source = "nisa"], index) => ({ id: `${audience}-${index + 1}`, audience, name, status, category, note, source })),
);

export function filterMahramRelations(audience: MahramAudience, status: MahramStatus | "all", query: string) {
  const term = normalizeIslamicSearch(query);
  return MAHRAM_RELATIONS.filter((relation) => relation.audience === audience && (status === "all" || relation.status === status) && normalizeIslamicSearch(`${relation.name} ${relation.note} ${relation.category}`).includes(term));
}
